"""Study 1 — original-S packet builder. Frozen before any formal build.

Estimand boundary (frozen protocol §3): S_t is the verbatim output of the benchmark's
own default prompt path, `SecodepltPythonInstruct.get_prompt(doc)` with
`include_security_policy=True`. This builder therefore has exactly two content
sources, both hash-pinned: the frozen sampling selection manifest, and the original
benchmark records it points to. Nothing else is read. In particular it never reads,
imports, or transits the writer package, any candidate specification, or any Round-2
coding artifact — Study 1 measures the benchmark as shipped, not the blinded variants,
and the data-flow audit holds this file to that boundary mechanically.

S_t is generated by EXECUTING THE BENCHMARK'S OWN SHIPPED SOURCE: instruct.py is
byte-verified against a pinned SHA256 and exec'd with its heavy third-party imports
stubbed (they are not touched by get_prompt). A mechanical re-rendering from the same
template pieces is asserted byte-equal for every record, which both cross-checks the
stub execution and yields the labelled segments the scorer's quote-location analysis
needs.

Case extraction replicates, self-contained, the mechanical rule of the frozen Round-2
builder (subprocess-exec of setup+testcases, dump situation/input/expected). It is a
re-implementation with the same rule, not an import: importing the Round-2 builder
would put writer-artifact paths into this file's import graph.

The formal build runs only with --approved-packet-build, which is withheld until the
tooling freeze is approved. Every seed derives from the frozen Study-1 protocol hash.
"""

